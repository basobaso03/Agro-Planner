export const RUNWAY_TEMPLATE_NAMES_STORAGE_KEY = 'runway_template_custom_names';

export function getTemplateNameOverrides(): Record<string, string> {
  if (typeof window === 'undefined') return {};
  try {
    const raw = window.localStorage.getItem(RUNWAY_TEMPLATE_NAMES_STORAGE_KEY);
    return raw ? JSON.parse(raw) : {};
  } catch {
    return {};
  }
}

export function setTemplateNameOverride(templateId: string, newName: string): void {
  if (typeof window === 'undefined') return;
  try {
    const current = getTemplateNameOverrides();
    current[templateId] = newName.trim();
    window.localStorage.setItem(RUNWAY_TEMPLATE_NAMES_STORAGE_KEY, JSON.stringify(current));
  } catch {
    // Non-fatal if storage unavailable
  }
}

export function getAvailableTemplates(
  orgType?: 'AGRO_FARMING' | 'GENERAL_VENTURE' | 'ANY',
  orgSavedTemplates: RunwayTemplate[] = []
): RunwayTemplate[] {
  const overrides = getTemplateNameOverrides();
  const all = [...BUILT_IN_RUNWAY_TEMPLATES, ...orgSavedTemplates].map((t) => {
    if (overrides[t.id]) {
      return { ...t, name: overrides[t.id] };
    }
    return t;
  });
  if (!orgType || orgType === 'ANY') return all;
  return all.filter((t) => t.orgType === orgType);
}
